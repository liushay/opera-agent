def generate_all_docs():
    """批量生成戏曲文档并入库"""
    print("=" * 60)
    print("开始批量生成戏曲主题知识库文档")
    print("=" * 60)

    # 清空旧知识库目录中同名文件
    for fname in os.listdir(KB_DIR):
        os.remove(os.path.join(KB_DIR, fname))

    total_files = 0
    for genre, theme, fname, content in OPERA_DOCS:
        file_path = os.path.join(KB_DIR, fname)
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"生成文档: {fname}")
        total_files += 1

        # 入库（Chroma + BM25）
        try:
            kb.add_file_increment(file_path)
            print(f"  入库成功: {fname}")
        except Exception as e:
            print(f"  入库失败: {fname} - {e}")

    # 重建 BM25 索引
    print("\n重建 BM25 索引...")
    kb.rebuild_full_bm25()
    print("BM25 索引重建完成")

    # 显示知识库统计
    data = kb.vector_store.get()
    print(f"\n向量库文档总数: {len(data['ids'])}")
    print(f"生成文档总数: {total_files}")
    print("=" * 60)
    print("戏曲主题知识库文档生成与入库完成！")

